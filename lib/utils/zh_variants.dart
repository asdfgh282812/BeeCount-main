/// 把字串摺疊成可互相比對的形式:繁轉簡 + 小寫 + 去除空白與常見分隔符。
///
/// 不在表內的字原樣通過,所以對英文、數字、未收錄的漢字都是安全的。
String foldZh(String input) {
  final buf = StringBuffer();
  for (final ch in input.characters_) {
    if (ch == ' ' || ch == '　' || ch == '-' || ch == '_' || ch == '/') {
      continue;
    }
    buf.write(kTradToSimp[ch] ?? ch);
  }
  return buf.toString().toLowerCase();
}

extension on String {
  /// 逐字元(以 UTF-16 code unit 為單位就夠用 —— 本表全是 BMP 內的漢字)。
  Iterable<String> get characters_ sync* {
    for (var i = 0; i < length; i++) {
      yield this[i];
    }
  }
}
